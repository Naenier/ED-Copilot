package reference

import (
	"fmt"

	v "github.com/Naenier/ED-Copilot/internal/value"
)

func experimentalModifiers(stats v.M, key string) []Property {
	var result []Property
	for _, modifier := range v.Rows(v.At(stats, "effects", key)) {
		stat := v.Str(modifier["label"])
		label := experimentalLabels[stat]
		if label == "" {
			continue
		}
		value := v.Num(modifier["value"])
		formatted := fmt.Sprintf("%+.4g%%", value*100)
		if stat == "Jitter" {
			formatted = fmt.Sprintf("%+g°", value)
		} else if modifier["method"] == "additive" {
			formatted = fmt.Sprintf("%+.4g п. п.", value*100)
		}
		result = append(result, Property{Label: label, Value: formatted})
	}
	return result
}

