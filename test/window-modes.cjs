"use strict";
const assert = require("node:assert/strict");
const { WINDOW_MODES, WindowModeError, isWindowMode, normalizeWindowMode, requiresFrameChange, windowModePlan } = require("../electron/windowModes.cjs");
const display = { bounds: { x: 0, y: 0, width: 1920, height: 1080 }, workArea: { x: 0, y: 0, width: 1920, height: 1040 } };
const saved = { x: 250, y: 160, width: 1200, height: 800, maximized: false };
assert.deepEqual(WINDOW_MODES, ["windowed", "fullscreen", "borderless"]);
for (const mode of WINDOW_MODES) assert.equal(isWindowMode(mode), true);
for (const invalid of ["WINDOWED", "full-screen", "windowed ", {}, true, undefined]) assert.equal(isWindowMode(invalid), false);
assert.equal(normalizeWindowMode("bad profile value"), "windowed");
assert.equal(normalizeWindowMode("fullscreen"), "fullscreen");
assert.throws(() => windowModePlan("maximized"), WindowModeError);
assert.throws(() => windowModePlan(null), WindowModeError);

let plan = windowModePlan("windowed", { normalBounds: saved, display });
assert.deepEqual(plan.bounds, { x: 250, y: 160, width: 1200, height: 800 });
assert.equal(plan.options.frame, true); assert.equal(plan.options.fullscreen, false); assert.equal(plan.requiresRecreation, false);
assert.equal(plan.options.resizable, true); assert.equal(plan.options.movable, true);
assert.equal(plan.options.minimizable, true); assert.equal(plan.options.closable, true);

plan = windowModePlan("fullscreen", { previousMode: "windowed", normalBounds: saved, display });
assert.deepEqual(plan.bounds, display.bounds);
assert.equal(plan.options.fullscreen, true); assert.equal(plan.options.frame, true); assert.equal(plan.requiresRecreation, false);
assert.deepEqual(plan.normalBounds, saved, "Native fullscreen geometry must not overwrite normal bounds");

const borderless = windowModePlan("borderless", { previousMode: "fullscreen", normalBounds: saved, display });
assert.deepEqual(borderless.bounds, display.workArea, "Borderless keeps the taskbar work area available");
assert.equal(borderless.options.frame, false); assert.equal(borderless.options.fullscreen, false);
assert.equal(borderless.options.thickFrame, false); assert.equal(borderless.options.resizable, false);
assert.equal(borderless.options.movable, false); assert.equal(borderless.requiresRecreation, true);
assert.deepEqual(borderless.normalBounds, saved);
assert.equal(windowModePlan("windowed", { previousMode: "borderless", normalBounds: saved, display }).requiresRecreation, true);
assert.equal(requiresFrameChange("fullscreen", "windowed"), false);
assert.equal(requiresFrameChange("borderless", "borderless"), false);
assert.equal(requiresFrameChange("corrupt preference", "borderless"), true);

const left = { bounds: { x: -2560, y: -300, width: 2560, height: 1440 }, workArea: { x: -2560, y: -260, width: 2560, height: 1400 } };
plan = windowModePlan("borderless", { display: left, normalBounds: { x: -2100, y: -200, width: 1000, height: 700 } });
assert.deepEqual(plan.bounds, left.workArea);
assert.equal(plan.normalBounds.x, -2100); assert.equal(plan.normalBounds.y, -200);
plan = windowModePlan("windowed", { display, normalBounds: { x: -9000, y: 9000, width: 9000, height: 9000 } });
assert.deepEqual(plan.bounds, display.workArea, "Restoring a disconnected or oversized window stays inside a connected work area");
const tiny = { bounds: { x: 50, y: 100, width: 640, height: 480 }, workArea: { x: 50, y: 100, width: 640, height: 440 } };
plan = windowModePlan("windowed", { display: tiny, normalBounds: saved });
assert.deepEqual(plan.bounds, tiny.workArea);
assert.equal(plan.options.minWidth, 640); assert.equal(plan.options.minHeight, 440);
const maximized = { ...saved, maximized: true };
assert.equal(windowModePlan("windowed", { display, normalBounds: maximized }).maximize, true);
assert.equal(windowModePlan("fullscreen", { display, normalBounds: maximized }).maximize, false);
assert.equal(windowModePlan("borderless", { display, normalBounds: maximized }).maximize, false);
assert.deepEqual(saved, { x: 250, y: 160, width: 1200, height: 800, maximized: false }, "Planning does not mutate persisted values");
assert(windowModePlan().bounds.width > 0);
console.log("Window modes: strict modes, framed/frameless transition plans, fullscreen/workarea distinction, normal-bounds preservation and multi-monitor clamping passed.");
