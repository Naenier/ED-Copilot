"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { EventEmitter } = require("node:events");
const { PassThrough } = require("node:stream");
const { writeFileAtomic } = require("../electron/atomicWrite.cjs");
const { createWindowState, clampBounds, enableZoom } = require("../electron/windowState.cjs");
const { hudWindowOptions } = require("../electron/hudWindowOptions.cjs");
const { isGame, isGameOrOwn, parseForegroundLine, nativeWatcherPath, monitorScript, watchForeground, watchForegroundOffMain } = require("../electron/foregroundWatch.cjs");
const { childWindowKind, galaxyWindowBounds } = require("../electron/childWindows.cjs");
const folder = fs.mkdtempSync(path.join(__dirname, "runtime-test-"));
const primary = { workArea: { x: 0, y: 0, width: 1920, height: 1040 } };
const secondary = { workArea: { x: -1920, y: 0, width: 1920, height: 1080 } };
try {
  const filename = path.join(folder, "nested", "settings.json");
  writeFileAtomic(filename, '{"value":1}');
  writeFileAtomic(filename, '{"value":2}');
  assert.deepEqual(JSON.parse(fs.readFileSync(filename, "utf8")), { value: 2 });
  assert.deepEqual(fs.readdirSync(path.dirname(filename)), ["settings.json"]);
  assert.throws(() => writeFileAtomic(filename, Symbol("invalid")));
  assert.equal(JSON.parse(fs.readFileSync(filename, "utf8")).value, 2, "Failed update preserves the last complete file");
  assert.deepEqual(fs.readdirSync(path.dirname(filename)), ["settings.json"]);

  const screen = { getAllDisplays: () => [primary, secondary] };
  const windows = createWindowState(() => folder, { screen });
  assert.equal(windows.readWindowState("app"), null);
  windows.saveWindowState("app", { x: -1600, y: 50, width: 1000, height: 700, maximized: true });
  assert.deepEqual(windows.readWindowState("app"), { x: -1600, y: 50, width: 1000, height: 700, maximized: true });
  screen.getAllDisplays = () => [primary];
  const moved = windows.readWindowState("app");
  assert.deepEqual(moved, { x: 460, y: 170, width: 1000, height: 700, maximized: true }, "Disconnected monitor recenters on a connected display");
  assert.deepEqual(clampBounds({ x: -99999, y: 99999, width: 9000, height: 5000 }, [primary]), { x: 0, y: 0, width: 1920, height: 1040, maximized: false });
  assert.equal(clampBounds({ x: NaN, y: 0, width: 900, height: 700 }, [primary]), null);
  assert.equal(windows.saveWindowState("__proto__", { x: 0, y: 0, width: 900, height: 700 }), false);
  assert.equal(windows.saveWindowState("constructor", { x: 0, y: 0, width: 900, height: 700 }), false);
  const win = new EventEmitter();
  Object.assign(win, { getNormalBounds: () => ({ x: 30, y: 40, width: 1200, height: 800 }), isMaximized: () => true, getBounds: () => primary.workArea });
  const untrack = windows.trackWindowState("app", win);
  win.emit("resize"); win.emit("close"); untrack();
  assert.equal(windows.readWindowStates().app.width, 1200, "Maximized windows preserve their normal size");
  assert.equal(windows.readWindowStates().app.maximized, true);
  fs.writeFileSync(windows.windowStatePath(), "bad JSON");
  assert.equal(windows.readWindowState("app"), null);

  const contents = new EventEmitter();
  let zoom = 1, prevented = 0;
  contents.getZoomFactor = () => zoom; contents.setZoomFactor = value => { zoom = value; };
  enableZoom({ webContents: contents });
  const emitKey = input => contents.emit("before-input-event", { preventDefault: () => { prevented++; } }, { type: "keyDown", ...input });
  emitKey({ key: "+", control: true }); assert.equal(zoom, 1.1);
  emitKey({ key: "-", control: true }); assert.equal(zoom, 1);
  for (let i = 0; i < 30; i++) emitKey({ code: "NumpadAdd", control: true });
  assert.equal(zoom, 2.5);
  emitKey({ key: "0", control: true }); assert.equal(zoom, 1);
  const beforeIgnored = prevented;
  emitKey({ key: "+", control: true, alt: true }); emitKey({ key: "+", control: true, type: "keyUp" });
  assert.equal(prevented, beforeIgnored);

  const hud = hudWindowOptions(410, 560, "icon.png", "preload.cjs");
  assert.equal(hud.transparent, true); assert.equal(hud.focusable, false); assert.equal(hud.skipTaskbar, true);
  assert.equal(hud.webPreferences.sandbox, true); assert.equal(hud.webPreferences.nodeIntegration, false);
  assert.equal(hud.webPreferences.contextIsolation, true);
  assert.equal(childWindowKind("http://127.0.0.1:7122/galaxy.html"), "galaxy");
  assert.equal(childWindowKind("invalid"), null);
  const child = galaxyWindowBounds({ x: -500, y: -500, width: 3000, height: 2000 }, primary.workArea);
  assert.deepEqual(child, { x: 0, y: 0, width: 1920, height: 1040 });

  assert.equal(isGame("EliteDangerous64.exe"), true);
  assert.equal(isGame("C:\\Games\\EliteDangerous64.exe"), true);
  assert.equal(isGame("EDLaunch.exe"), false);
  assert.equal(isGame("badEliteDangerous64"), false);
  assert.equal(isGameOrOwn("ED Copilot.exe", ["ed copilot"]), true);
  assert.equal(isGameOrOwn("Chrome.exe", ["ed copilot"]), false);
  assert.deepEqual(parseForegroundLine('{"name":"EliteDangerous64","at":{"x":-960,"y":540}}'), { name: "elitedangerous64", at: { x: -960, y: 540 } });
  assert.deepEqual(parseForegroundLine("EliteDangerous64\t960,540"), { name: "elitedangerous64", at: { x: 960, y: 540 } });
  assert.equal(parseForegroundLine('{"name":"bad\\nname"}').name, null);
  assert.equal(parseForegroundLine('{"name":"Chrome","at":{"x":"1","y":2}}').at, null);
  assert.equal(nativeWatcherPath(), null);
  assert.throws(() => monitorScript(-1));
  let launchArgs, killed = false;
  const processEvents = new EventEmitter(); processEvents.stdout = new PassThrough(); processEvents.kill = () => { killed = true; };
  const records = [];
  const monitor = watchForeground((name, at) => records.push({ name, at }), null, { platform: "win32", spawn: (executable, args, options) => { launchArgs = { executable, args, options }; return processEvents; } });
  processEvents.stdout.write('{"name":"EliteDangerous64","at":{"x":1000,"y":500}}\n');
  assert.deepEqual(records[0], { name: "elitedangerous64", at: { x: 1000, y: 500 } });
  assert.equal(launchArgs.options.windowsHide, true);
  const script = Buffer.from(launchArgs.args.at(-1), "base64").toString("utf16le");
  assert(script.includes("CopilotWindowProbe") && script.includes("GetWindowThreadProcessId"));
  assert(!script.includes("ExecutionPolicy") && !launchArgs.args.includes("-ExecutionPolicy"));
  monitor.stop(); assert.equal(killed, true);
  const unsupported = [];
  watchForeground((name, at) => unsupported.push({ name, at }), null, { platform: "linux" }).stop();
  assert.deepEqual(unsupported, [{ name: null, at: null }]);
  console.log("Independent runtime: atomic replacement, monitor disconnect/geometry, zoom, overlay isolation and read-only foreground monitor contracts passed.");
} finally {
  const resolved = path.resolve(folder);
  if (path.dirname(resolved) !== path.resolve(__dirname) || !path.basename(resolved).startsWith("runtime-test-")) throw new Error("Unexpected fixture path");
  fs.rmSync(resolved, { recursive: true });
}
