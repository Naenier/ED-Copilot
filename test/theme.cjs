"use strict";
const fs = require("node:fs");
const path = require("node:path");
const assert = require("node:assert/strict");
const { normalizeTheme, derivePalette, readGamePalette, parseXmlMatrix, parseEdhmMatrix, parseEdhmColors, transform, ThemeError } = require("../lib/theme.cjs");
const root = fs.mkdtempSync(path.join(__dirname, "theme-test-"));
const xml = values => `<GraphicsConfig><GUIColour><Default><MatrixRed>${values[0].join(", ")}</MatrixRed><MatrixGreen>${values[1].join(", ")}</MatrixGreen><MatrixBlue>${values[2].join(", ")}</MatrixBlue></Default></GUIColour></GraphicsConfig>`;
const identity = [[1,0,0],[0,1,0],[0,0,1]], blue = [[0,.6,1],[0,0,0],[1,0,0]];
async function run() {
  assert.equal(derivePalette({}).accent, "#28a0f0");
  assert.equal(derivePalette({ mode: "preset", preset: "orange" }).accent, "#ff8a24");
  assert.equal(transform("#ff7f00", blue), "#0099ff", "Elite matrix row orientation is input RGB contributions");
  assert.equal(transform("#123456", identity), "#123456");
  assert.equal(derivePalette({ mode: "matrix", matrix: blue }).accent, "#0099ff");
  assert.equal(normalizeTheme({ mode: "custom", colors: { accent: "#ABCDEF" }, overlayOpacity: .635 }).overlayOpacity, .64);
  assert.equal(derivePalette({ mode: "custom", colors: { accent: "#ABCDEF" } }).accent, "#abcdef");
  for (const invalid of [{ colors: { accent: "red; background: url(https://invalid)" } }, { matrix: [[1,0,0],[0,1,0],[0,0,3]] },
    { matrix: [[NaN,0,0],[0,1,0],[0,0,1]] }, { overlayOpacity: .39 }, { overlayOpacity: "0.8" }, { mode: "auto" }]) assert.throws(() => normalizeTheme(invalid), ThemeError);
  assert.deepEqual(parseXmlMatrix(xml(blue)), blue);
  assert.deepEqual(parseXmlMatrix(`<!-- <MatrixRed>99,99,99</MatrixRed> -->${xml(identity)}`), identity);
  assert.equal(parseXmlMatrix("<GraphicsConfig/>"), null);
  assert.throws(() => parseXmlMatrix("<!DOCTYPE GraphicsConfig [<!ENTITY file SYSTEM 'file:///x'>]><GraphicsConfig/>"), ThemeError);
  assert.throws(() => parseXmlMatrix("<MatrixRed>1,0,0</MatrixRed>"), ThemeError);
  const profile = "[Constants]\nx150=.15\ny150=.63\nz150=.94\nx151=.05\ny151=0\nz151=0\nx152=.86\ny152=.43\nz152=.12\n";
  const startup = "[Constants]\nw206=100\nw75=100\ny78=100\ny104=100\ny139=100\n";
  const advanced = "[Constants]\nx208=.0212\ny208=.3515\nz208=.8714\nx77=.7454\ny77=.7454\nz77=.7454\nx82=1\ny82=1\nz82=1\nx172=.8714\ny172=.3515\nz172=.0212\nx246=.0212\ny246=.3515\nz246=.8714\nx247=.8714\ny247=.0091\nz247=.0091\n";
  assert.deepEqual(parseEdhmMatrix(profile), [[.15,.63,.94],[.05,0,0],[.86,.43,.12]]);
  assert.equal(parseEdhmColors(startup, advanced).colors.accent, "#28a0f0", "EDHM linear RGB channels convert to sRGB");
  assert.equal(parseEdhmColors(startup, advanced).colors.text, "#e0e0e0");
  assert.equal(parseEdhmColors(startup, advanced).colors.warn, "#f0a028");
  assert.equal(parseEdhmColors("[Constants]\nw206=199\n", advanced).imported.length, 0, "custom overrides apply only in active custom mode");
  const gameDir = path.join(root, "game"), edhm = path.join(gameDir, "EDHM-ini");
  fs.mkdirSync(edhm, { recursive: true });
  for (const [name, raw] of [["XML-Profile.ini", profile], ["Startup-Profile.ini", startup], ["Advanced.ini", advanced], ["ThemeSettings.json", JSON.stringify({ credits: { theme: "Synthetic blue HUD" } })]]) fs.writeFileSync(path.join(edhm, name), raw);
  const before = fs.readFileSync(path.join(edhm, "XML-Profile.ini"));
  const imported = await readGamePalette({ gameDir, homeDir: root, now: 1700000000000 });
  assert.equal(imported.settings.mode, "game"); assert.equal(imported.source.kind, "edhm");
  assert.equal(imported.source.name, "Synthetic blue HUD"); assert.equal(imported.palette.accent, "#28a0f0");
  assert.equal(imported.source.files.length, 3); assert.equal(imported.source.importedAt, "2023-11-14T22:13:20.000Z");
  assert(fs.readFileSync(path.join(edhm, "XML-Profile.ini")).equals(before), "game files remain unchanged");
  assert.equal((await readGamePalette({ filePath: path.join(edhm, "Advanced.ini") })).palette.accent, "#28a0f0");
  const selected = path.join(root, "GraphicsConfigurationOverride.xml"); fs.writeFileSync(selected, xml(blue));
  const importedXml = await readGamePalette({ filePath: selected });
  assert.equal(importedXml.source.kind, "xml"); assert.equal(importedXml.palette.accent, "#0099ff");
  await assert.rejects(() => readGamePalette({ filePath: path.join(root, "frontier-tokens.enc") }), /Выберите/);
  fs.writeFileSync(selected, "<GraphicsConfig/>");
  await assert.rejects(() => readGamePalette({ filePath: selected }), /не найдена/);
  const unapplied = path.join(root, "EDHM_UI/ODYSS/EDHM/EDHM-Ini");
  fs.mkdirSync(unapplied, { recursive: true }); fs.writeFileSync(path.join(unapplied, "XML-Profile.ini"), profile);
  await assert.rejects(() => readGamePalette({ gameDir: path.join(root, "missing-game"), homeDir: root }), /не найдена/, "unlinked EDHM UI cache is not treated as the active game configuration");
  console.log("Theme: palette validation, Elite matrix orientation, EDHM active custom colors/gamma, XML+INI import, source metadata and read-only files passed.");
}
run().then(() => {
  if (path.dirname(path.resolve(root)) !== path.resolve(__dirname) || !path.basename(root).startsWith("theme-test-")) throw new Error("Unsafe test cleanup");
  fs.rmSync(root, { recursive: true });
}).catch(error => { console.error(error); process.exitCode = 1; });
